// Real components, synthetic local fixtures, all server mutations stubbed by ui-recovery-preview.cjs.
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const assert = require('node:assert/strict');
const { firefox } = require('playwright');
const output = path.join(process.cwd(), 'audit-artifacts/ui-recovery-01/correction-2');
const fixture = path.join(process.cwd(), 'audit-artifacts/ui-recovery-01/local');

(async () => {
  fs.mkdirSync(output, { recursive: true });
  const server = http.createServer((req, res) => {
    const name = req.url === '/' ? 'index.html' : req.url.slice(1);
    if (!['index.html','ui.js','ui.css'].includes(name)) { res.writeHead(404).end(); return; }
    res.setHeader('Content-Type', name.endsWith('.js') ? 'text/javascript' : name.endsWith('.css') ? 'text/css' : 'text/html');
    res.end(fs.readFileSync(path.join(fixture, name)));
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await firefox.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const tests = [];
  const capture = name => page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true });
  const calls = name => page.evaluate(n => (window.__actionCalls ?? []).filter(c => c.name === n), name);
  try {
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.getByLabel('Etapas PREBID').getByRole('button', { name: 'APU', exact: true }).click();
    assert.equal(await page.locator('select').count(), 0);
    await page.getByRole('combobox').first().click();
    await page.getByRole('listbox').waitFor();
    await capture('prebid-partida-open');
    await page.keyboard.press('Escape');
    await page.getByRole('combobox').nth(1).click();
    await page.getByRole('option', { name: /Cemento/ }).click();
    await page.locator('input[name=quantity]').fill('0.5');
    await page.getByRole('button', { name: 'Guardar APU', exact: true }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'saveWorkspaceApuLineAction'));
    const apu = (await calls('saveWorkspaceApuLineAction'))[0];
    assert.equal(apu.args[1].productoId, 'product-1');
    assert.equal(apu.args[1].budgetItemId, 'item-1');
    assert.equal(apu.args[1].quantity, 0.5);
    tests.push('PREBID actual APU payload product/item/quantity');
    await page.getByLabel('Etapas PREBID').getByRole('button', { name: /Presupuesto/ }).click();
    const charge = page.getByRole('combobox').first();
    await charge.focus(); await page.keyboard.press('ArrowDown');
    await page.getByRole('listbox').waitFor();
    await page.keyboard.press('End'); await page.keyboard.press('Enter');
    assert.match(await charge.innerText(), /Monto fijo/);
    tests.push('Radix Arrow/End/Enter/Escape keyboard interaction');
    await page.getByLabel('Etapas PREBID').getByRole('button', { name: 'Costeo y evidencia' }).click();
    await page.getByRole('checkbox', { name: 'Proveedor de referencia' }).check();
    await page.getByRole('button', { name: 'Solicitar cotización de referencia' }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'createWorkspaceDiscoveryAction'));
    const discovery = (await calls('createWorkspaceDiscoveryAction'))[0].args;
    assert.equal(discovery[1], 'product-1'); assert.deepEqual(discovery[2], ['provider-1']);
    tests.push('Existing RFQ discovery product/provider payload');

    await page.getByRole('button', { name: 'RFQ', exact: true }).click();
    await page.getByRole('button', { name: 'Abrir RFQ', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByRole('combobox').first().click();
    await page.getByRole('option', { name: /Descubrir costos/ }).click();
    const product = dialog.getByRole('combobox', { name: 'Producto 1', exact: true });
    await product.click(); await page.getByRole('listbox').waitFor();
    await capture('rfq-product-open');
    await page.getByRole('option', { name: /Arena/ }).click();
    await dialog.getByRole('spinbutton').first().fill('3');
    await dialog.getByRole('button', { name: 'Confirmar creación de RFQ', exact: true }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'createRfq'));
    const rfq = (await calls('createRfq'))[0].args[0];
    assert.equal(rfq.purpose, 'COST_DISCOVERY');
    assert.equal(JSON.parse(rfq.items)[0].producto_id, 'product-2');
    tests.push('RFQ actual catalog selection action payload');
    await page.keyboard.press('Escape');

    await page.getByRole('button', { name: 'Personal', exact: true }).click();
    await page.getByRole('button', { name: '+ Registrar parte diario', exact: true }).click();
    await page.getByRole('combobox', { name: 'Partida', exact: true }).click();
    await page.getByRole('option', { name: /Mampostería/ }).click();
    await page.getByRole('combobox', { name: 'Categoría (jornal)', exact: true }).click();
    await page.getByRole('option', { name: 'Oficial', exact: true }).click();
    await page.locator('input[name=worker_name]').fill('Fixture worker');
    await page.locator('input[name=hours]').fill('8');
    await page.getByRole('button', { name: 'Registrar', exact: true }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'addLaborEntry'));
    const personnel = (await calls('addLaborEntry'))[0].args[1];
    assert.equal(personnel.budget_item_id, 'item-1'); assert.equal(personnel.labor_rate_id, 'rate-1');
    tests.push('Personnel actual FormData item/category');
    await page.keyboard.press('Escape');

    await page.getByRole('button', { name: 'Clima / Libro', exact: true }).click();
    await page.getByRole('button', { name: 'Corregir / Override', exact: true }).click();
    const classification = page.getByRole('combobox', { name: 'Clasificación final', exact: true });
    await classification.click(); await page.getByRole('listbox').waitFor();
    await capture('climate-classification-open');
    await page.getByRole('option', { name: 'No trabajable por otra causa', exact: true }).click();
    const reason = page.getByRole('combobox', { name: 'Causa', exact: true });
    await reason.click(); await page.getByRole('option', { name: 'Acceso bloqueado', exact: true }).click();
    await page.getByRole('button', { name: 'Guardar override', exact: true }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'overrideWeatherWorkday'));
    const override = (await calls('overrideWeatherWorkday'))[0].args[2];
    assert.equal(override.classification, 'NON_WORKABLE_OTHER'); assert.equal(override.reasonCode, 'ACCESS_BLOCKED');
    tests.push('Climate exact canonical enum payload');
    await capture('climate-review-manual');
    await page.getByText('HISTÓRICO LEGACY — SOLO LECTURA', { exact: true }).scrollIntoViewIfNeeded();
    await capture('legacy-read-only');
    assert.equal(await page.locator('select').count(), 0);
    await page.getByRole('combobox', { name: 'Tipo entrada manual' }).click();
    await page.getByRole('option', { name: 'Día de lluvia', exact: true }).click();
    await page.getByRole('button', { name: 'Guardar decisión manual' }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'createOtherWorkday'));
    assert.equal((await calls('createOtherWorkday'))[0].args[3], 'NON_WORKABLE_RAIN');
    tests.push('Manual canonical entry selected classification');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Residente', exact: true }).click();
    await page.getByRole('button', { name: 'Registrar lluvia', exact: true }).click();
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Registrar lluvia' && b.getAttribute('aria-pressed') === 'true'));
    assert.equal(await page.getByRole('button', { name: 'Enviar medición y foto' }).isDisabled(), true);
    await capture('resident-mobile-rain');
    assert.equal(errors.length, 0, errors.join('\n'));
    tests.push('Mobile resident photo required; no browser runtime fatal');
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.goto(`http://127.0.0.1:${server.address().port}/#outcome`);
    await page.reload();
    await page.getByLabel('Etapas PREBID').getByRole('button', { name: 'Versiones y resultado' }).click();
    await page.getByRole('combobox', { name: 'Resultado', exact: true }).click();
    await page.getByRole('option', { name: 'PERDIDA', exact: true }).click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Confirmar resultado', exact: true }).click();
    await page.waitForFunction(() => window.__actionCalls?.some(c => c.name === 'recordPrebidOutcomeAction'));
    assert.equal((await calls('recordPrebidOutcomeAction'))[0].args[1], 'PERDIDA');
    tests.push('PREBID actual Resultado FormData');
    await page.goto(`http://127.0.0.1:${server.address().port}/#readonly`);
    await page.reload();
    await page.getByLabel('Etapas PREBID').getByRole('button', { name: 'APU', exact: true }).click();
    assert.equal(await page.getByRole('combobox').nth(1).isDisabled(), true);
    const disabledPayload = await page.locator('input[name=product]').evaluate(input => Object.fromEntries(new FormData(input.form)));
    assert.equal(disabledPayload.product, undefined);
    assert.equal(await page.locator('select').count(), 0);
    tests.push('Read-only disabled Select excluded from actual FormData');
    fs.writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify({ browser: 'Windows Firefox / Playwright', fixtureOnly: true, productionMutations: 0, tests, errors }, null, 2));
    console.log(JSON.stringify({ state: 'PASS', tests: tests.length, browser: 'Windows Firefox', screenshots: output }));
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
